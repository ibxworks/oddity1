// ─── Unified Annotation Type ───

export type AnnotationType = OverviewLabel | DepthType | "user_written";

export type TextQuoteSelector = {
  type: "TextQuoteSelector";
  exact: string;
  prefix?: string;
  suffix?: string;
};

export type AnnotationContent = {
  note: string;
  why_it_matters?: string;
  question?: string;
  /** Whether the AI introduced this claim without the user asking. Sally peer-review only. */
  ai_introduced?: boolean;
  /** @deprecated No longer generated by LLM, kept for cached data backward compat */
  suggestions?: string[];
};

export type Annotation = {
  id: string;
  mode: AnnotationMode;
  type: AnnotationType;
  /** LLM-generated title (overview chunks). Falls back to ANNOTATION_LABELS[type] when absent. */
  label?: string;
  /** LLM-assigned verdict for depth annotations. Drives margin note / highlight color. */
  verdict?: Verdict;
  anchor: TextQuoteSelector;
  content: AnnotationContent;
  /** Chunk boundaries for overview mode — marks the start and end of the text chunk this annotation covers. */
  chunk?: {
    start: TextQuoteSelector;
    end: TextQuoteSelector;
  };
};

export type AnnotationResponse = {
  success: boolean;
  cached: boolean;
  annotations: Annotation[];
  feedback?: AnnotationFeedback[];
};

// ─── Feedback ───

export type FeedbackType = "thumbs_up" | "thumbs_down" | "reply";

export type AnnotationFeedback = {
  id: string;
  annotation_id: string;
  feedback_type: FeedbackType;
  reply_text: string | null;
  created_at: string;
};

// ─── Annotation Style ───

export type AnnotationFont =
  | "default"
  | "fraunces"
  | "kalam"
  | "helvetica"
  | "arial"
  | "georgia";
export type AnnotationFontSize = "small" | "default" | "large";

// ─── Site Adapter Registry ───

export type StabilitySignal = {
  type: "selector_appears" | "selector_disappears" | "attribute_change";
  target_selector: string;
  attribute?: string;
  value?: string;
};

export type SiteAdapter = {
  id: string;
  hostname_pattern: string;
  content_selectors: string[];
  response_selector: string | null;
  stability_signal: StabilitySignal | null;
  excluded_selectors: string[];
  extraction_mode: "adapter" | "readability" | "custom_heuristic";
  enabled: boolean;
  updated_at: string;
};

// ─── User ───

export type UserTier = "free" | "pro";

export type UserProfile = {
  id: string;
  display_name: string | null;
  tier: UserTier;
  preferences: UserPreferences;
  created_at: string;
};

export type UserPreferences = {
  enabled?: boolean;
  annotation_mode?: AnnotationMode;
  depth_personality?: DepthPersonality;
  purpose?: UserPurpose | string;
  visible_types?: AnnotationType[];
  enabled_sites?: string[];
  annotation_font?: AnnotationFont;
  annotation_font_size?: AnnotationFontSize;
};

