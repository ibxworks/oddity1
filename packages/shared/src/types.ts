// ─── Annotation Modes ───

export type AnnotationMode = 'overview' | 'depth';
export type ViewMode = 'overview' | 'depth' | 'all';
export type DepthPersonality = 'terry' | 'jerry' | 'sally';

// ─── Overview Labels ───

export type OverviewLabel =
  | 'core_claim'
  | 'evidence'
  | 'outcome'
  | 'background'
  | 'transition';

// ─── Depth Types ───

export type DepthType =
  // Terry / Sally skills
  | "caveat"
  | "counterargument"
  | "alternative"
  | "fallacy"
  | "criteria"
  | "perspective"
  | "consequence"
  | "insight"
  | "recall"
  | "translation"
  | "decision_making"
  // Jerry skills
  | "juxtaposition"
  | "outsider"
  | "fixation_breaker"
  | "incomplete_move"
  | "personal_hook"
  | "role_assignment"
  | "exaggeration"
  | "reverse_brainstorm"
  // Legacy (backward compat)
  | "study"
  | "vocabulary";

// ─── Unified Annotation Type ───

export type AnnotationType = OverviewLabel | DepthType | "user_written";

export type TextQuoteSelector = {
  type: "TextQuoteSelector";
  exact: string;
  prefix?: string;
  suffix?: string;
};

export type AnnotationContent = {
  note: string;
  why_it_matters?: string;
  question?: string;
  /** @deprecated No longer generated by LLM, kept for cached data backward compat */
  suggestions?: string[];
};

export type Annotation = {
  id: string;
  mode: AnnotationMode;
  type: AnnotationType;
  /** LLM-generated title (overview chunks). Falls back to ANNOTATION_LABELS[type] when absent. */
  label?: string;
  anchor: TextQuoteSelector;
  content: AnnotationContent;
  /** Chunk boundaries for overview mode — marks the start and end of the text chunk this annotation covers. */
  chunk?: {
    start: TextQuoteSelector;
    end: TextQuoteSelector;
  };
};

export type AnnotationUsage = {
  count: number;
  limit: number;
  already_counted: boolean;
};

export type AnnotationResponse = {
  success: boolean;
  cached: boolean;
  annotations: Annotation[];
  feedback?: AnnotationFeedback[];
  usage?: AnnotationUsage;
  upgrade?: boolean;
  upgrade_multiplier?: number;
};

// ─── Feedback ───

export type FeedbackType = "thumbs_up" | "thumbs_down" | "reply";

export type AnnotationFeedback = {
  id: string;
  annotation_id: string;
  feedback_type: FeedbackType;
  reply_text: string | null;
  created_at: string;
};

// ─── Annotation Style ───

export type AnnotationFont =
  | "default"
  | "fraunces"
  | "kalam"
  | "helvetica"
  | "arial"
  | "georgia";
export type AnnotationFontSize = "small" | "default" | "large";

// ─── Site Adapter Registry ───

export type StabilitySignal = {
  type: "selector_appears" | "selector_disappears" | "attribute_change";
  target_selector: string;
  attribute?: string;
  value?: string;
};

export type SiteAdapter = {
  id: string;
  hostname_pattern: string;
  content_selectors: string[];
  response_selector: string | null;
  input_selector: string | null;
  stability_signal: StabilitySignal | null;
  excluded_selectors: string[];
  extraction_mode: "adapter" | "readability" | "custom_heuristic";
  enabled: boolean;
  updated_at: string;
};

// ─── User ───

export type UserTier = "free" | "standard";

export type SubscriptionStatus =
  | "active"
  | "past_due"
  | "canceled"
  | "incomplete"
  | "trialing"
  | "unpaid"
  | null;

export type BillingInterval = "month" | "quarter" | "year" | null;

export type UserProfile = {
  id: string;
  display_name: string | null;
  tier: UserTier;
  subscription_status: SubscriptionStatus;
  billing_interval: BillingInterval;
  current_period_end: string | null;
  cancel_at_period_end: boolean;
  monthly_annotation_count: number;
  preferences: UserPreferences;
  created_at: string;
};

export type UserPreferences = {
  enabled?: boolean;
  annotation_mode?: AnnotationMode;
  depth_personality?: DepthPersonality;
  visible_types?: AnnotationType[];
  enabled_sites?: string[];
  annotation_font?: AnnotationFont;
  annotation_font_size?: AnnotationFontSize;
};

// ─── API Request/Response ───

export type AnnotateRequest = {
  url: string;
  content_hash: string;
  text: string;
  mode: AnnotationMode;
  personality?: DepthPersonality;
  word_count: number;
};

export type ReadingRegion = {
  id: string;
  element: string; // CSS selector or description for debugging
  text: string;
  wordCount: number;
  contentHash: string;
};

